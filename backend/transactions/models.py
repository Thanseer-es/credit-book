
import uuid

from django.db import models
from django.conf import settings
from django.core.validators import MinValueValidator
from decimal import Decimal

from shops.models import Shop
from customers.models import Customer


class LedgerTransaction(models.Model):

    class TransactionType(models.TextChoices):
        CREDIT = 'CREDIT', 'Credit'
        PAYMENT = 'PAYMENT', 'Payment'

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )

    shop = models.ForeignKey(
        Shop,
        on_delete=models.CASCADE,
        related_name='transactions'
    )

    customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name='transactions'
    )

    transaction_type = models.CharField(
        max_length=10,
        choices=TransactionType.choices
    )

    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.01"))]
    )

    description = models.TextField(blank=True)

    # Unique ID generated by the client.
    # Helps prevent duplicate transactions during offline sync.
    client_transaction_id = models.UUIDField()

    # A reversal is stored as a new transaction.
    # It references the original transaction.
    reversal_of = models.OneToOneField(
        'self',
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name='reversal'
    )

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        related_name='ledger_transactions'
    )

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=['shop', 'client_transaction_id'],
                name='unique_client_transaction_per_shop'
            )
        ]

        ordering = ['-created_at']

    def __str__(self):
        return (
            f"{self.customer.name} - "
            f"{self.transaction_type} - "
            f"{self.amount}"
        )
